import assert from 'node:assert/strict';
import { captchaViewport } from '../src/shared/captcha-layout.ts';
const box = { x: 80, y: 580, width: 320, height: 80, visible: true };
const bottom = captchaViewport(box, 800, 600)!;
assert.equal(bottom.visible, true);
assert.equal(bottom.bounds.height, 20, 'partially visible bottom must be clipped, not hidden');
const top = captchaViewport({ ...box, y: -25 }, 800, 600)!;
assert.equal(top.visible, true);
assert.equal(top.bounds.height, 55);
assert.equal(top.offsetY, 25);
assert.equal(captchaViewport({ ...box, y: 601 }, 800, 600)!.visible, false);
assert.equal(captchaViewport({ ...box, visible: false }, 800, 600)!.visible, false);
assert.equal(captchaViewport({ ...box, x: NaN }, 800, 600), null);
const sidebar = captchaViewport({ ...box, y: 100, clipLeft: 256 }, 800, 600)!;
assert.equal(sidebar.visible, true, 'an overlapping sidebar must not hide the entire widget');
assert.equal(sidebar.bounds.x, 256);
assert.equal(sidebar.bounds.width, 144);
assert.equal(sidebar.offsetX, 176);
assert.equal(captchaViewport({ ...box, y: 290 }, 800, 600, 2)!.bounds.height, 20);
console.log('Captcha viewport clipping passed (top/bottom edges, zoom, invalid bounds and overlays).');
