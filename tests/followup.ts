import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import type { DownloadItem } from 'electron';
import { trackDownload } from '../electron/downloads.ts';
import { createNoticePoller } from '../electron/notices.ts';
import { HttpClient } from '../electron/http.ts';
import type { CommunityNotification, DownloadProgress } from '../src/shared/types.ts';
const credentials = { username: 'alice', sessionId: 'test' };
const notice: CommunityNotification = { kind: 'mail', mentionId: 1, title: 'message', body: '' };
let now = 0, bbsCalls = 0, mailCalls = 0, online = false;
const poll = createNoticePoller(async channel => {
    if (channel === 'mail') { mailCalls++; return [notice]; }
    bbsCalls++;
    if (!online) throw new Error('fetch failed');
    return [{ ...notice, kind: 'bbs' }];
}, { now: () => now, delay: async () => {} });
assert.deepEqual(await poll(credentials), [notice]);
assert.equal(bbsCalls, 2, 'transient network failure retried once');
assert.equal(mailCalls, 1, 'mail still received when bbs unavailable');
await poll(credentials);
assert.equal(bbsCalls, 2, 'failed channel backs off');
online = true; now = 30000;
assert.equal((await poll(credentials)).length, 2, 'poll recovers without restarting app');
const first = poll(credentials), second = poll(credentials);
assert.equal(first, second, 'simultaneous polls are coalesced');
await first;
await poll({ ...credentials, username: 'bob' });
assert.equal(bbsCalls, 5, 'new account has independent backoff');
const item = new EventEmitter() as EventEmitter & { getSavePath(): string; getFilename(): string; getReceivedBytes(): number; getTotalBytes(): number; isPaused(): boolean };
let savedName = '', received = 0;
Object.assign(item, { getSavePath: () => savedName, getFilename: () => 'original.zip', getReceivedBytes: () => received, getTotalBytes: () => 100, isPaused: () => false });
const progress: DownloadProgress[] = [];
trackDownload(item as unknown as DownloadItem, value => progress.push(value));
assert.equal(progress[0].fileName, 'original.zip');
savedName = 'renamed.zip'; received = 40;
item.emit('updated', {}, 'progressing');
assert.equal(progress.at(-1)?.fileName, 'renamed.zip');
assert.equal(progress.at(-1)?.receivedBytes, 40);
item.emit('updated', {}, 'interrupted');
assert.equal(progress.at(-1)?.state, 'paused', 'temporary interruption is not reported as terminal failure');
received = 100; item.emit('done', {}, 'completed');
assert.equal(progress.at(-1)?.state, 'completed');
assert.equal(new Set(progress.map(p => p.id)).size, 1);
