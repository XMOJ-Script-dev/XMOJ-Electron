import assert from 'node:assert/strict';
import { unzipSync, strFromU8 } from 'fflate';
import type { HttpClient } from '../electron/http.ts';
import { collectAcCode, buildArchive, extensionForLanguage } from '../electron/sources.ts';
import { attachOpeningComment, canManageDiscussion, isDiscussionAdmin, quoteReply } from '../src/shared/discussion.ts';
import { isExternalWebUrl, isJudgeUrl } from '../src/shared/links.ts';
import { CommunityApi, createMemoryTokenStore } from '../electron/community.ts';
const row = (id: number, language: string) => `<tr><td></td><td>${id}</td><td><a href="userinfo.php?user=alice">alice</a></td><td><a href="problem.php?id=1000">1000</a></td><td><a href="reinfo.php?sid=${id}">正确</a></td><td>128</td><td>2</td><td><a href="showsource.php?id=${id}">${language}</a></td><td>12 B</td><td>2026-01-01 00:00:00</td><td>-</td></tr>`;
const calls: string[] = [];
const http = { get: async (value: string) => {
    const url = new URL(value); calls.push(value);
    if (url.pathname === '/getsource.php') return { status: 200, body: url.searchParams.get('id') === '2999' ? '<html>hidden</html>' : 'print(1)\n<!-- not-cached -->' };
    if (url.searchParams.get('problem_id') === '1001') return { status: 200, body: '<table id="result-tab"></table>' };
    return { status: 200, body: url.searchParams.has('top') ? `<table id="result-tab">${row(2998, 'Python3')}</table>` : `<table id="result-tab">${row(3000, 'C++')}${row(2999, 'Python3')}</table><a href="status.php?top=2999&prevtop=3000">下一页</a>` };
} } as unknown as HttpClient;
const progress: number[] = [];
const result = await collectAcCode(http, [1000, 1001, 1000], { user: 'alice', languages: ['Python'], onProgress: done => progress.push(done) });
assert.equal(result.entries[0].solutionId, 2998, 'older matching readable submission is selected');
assert.equal(result.entries.length, 1);
assert.deepEqual(result.skipped, [1001]);
assert.deepEqual(progress, [1, 2], 'skipped problems also advance progress; duplicates do not');
assert.ok(!calls.some(call => call.includes('getsource.php?id=3000')), 'excluded language is never fetched');
assert.equal(strFromU8(unzipSync(buildArchive(result.entries))['1000.py']), 'print(1)');
assert.equal(extensionForLanguage('JavaScript'), 'js');
assert.equal(extensionForLanguage('Java'), 'java');
await assert.rejects(() => collectAcCode({ get: async () => ({ status: 503, body: '' }) } as unknown as HttpClient, [1000], { user: 'alice' }), /导出失败/);
const detail = { Title: '标题保持不变', Reply: [{ ReplyID: 1, UserID: 'alice', Content: '> 主楼正文', ReplyTime: 1 }, { ReplyID: 2, Content: '回复' }] };
const moved = attachOpeningComment(detail);
assert.equal(moved.Title, detail.Title);
assert.equal(moved.Content, '> 主楼正文');
assert.equal(moved.RootReplyID, 1);
assert.equal(moved.UserID, 'alice');
assert.equal(attachOpeningComment({ Title: '标题', Reply: [{ ReplyID: 3, Content: '第二页' }] }, detail).Content, '> 主楼正文');
assert.equal(attachOpeningComment({ ...detail, Content: '已有独立正文' }).Content, '已有独立正文');
for (const url of ['https://xmoj.tech/', 'https://www.xmoj.tech/problem.php?id=1', 'https://static.xmoj.tech/image.png']) assert.ok(isJudgeUrl(url));
for (const url of ['https://example.com/', 'https://xmoj.tech.evil.example/', 'https://www.xmoj.tech@evil.example/']) assert.ok(isExternalWebUrl(url));
assert.ok(!isExternalWebUrl('javascript:alert(1)'));
const tokens = createMemoryTokenStore(); tokens.set('alice', 'mock-token');
let sent: Record<string, any> | null = null;
const api = new CommunityApi({ request: async (_url: string, options: { body: string }) => { sent = JSON.parse(options.body); return { status: 200, body: '{"Success":true,"Data":{}}' }; } } as unknown as HttpClient, tokens);
await api.newReply({ username: 'alice', sessionId: 'mock-session' }, 1, '内容', 'mock-captcha');
assert.equal((sent as unknown as { Data: { CaptchaSecretKey: string } }).Data.CaptchaSecretKey, 'mock-captcha');
console.log('AC export, language filters, pagination, opening comment, external links and captcha forwarding passed.');
assert.ok(isDiscussionAdmin('liushangchen'));
assert.ok(canManageDiscussion('admin', 'alice', true));
assert.ok(canManageDiscussion('alice', 'alice'));
assert.ok(!canManageDiscussion('alice', 'alice', true));
assert.ok(!canManageDiscussion('bob', 'alice'));
assert.ok(!canManageDiscussion('', undefined));
assert.equal(quoteReply('正文\n> 一层\n>> 二层', 'alice'), '> 正文\n> > 一层\n\n\n@alice ');
const { fetchSource } = await import('../electron/sources.ts');
for (const marker of ['<!--not cached-->', '<!-- not-cached -->']) {
    const client = (body: string) => ({ get: async () => ({ status: 200, body }) }) as unknown as HttpClient;
    assert.equal(await fetchSource(client(`int main() {}\n${marker}\n\n \n`), 1), 'int main() {}');
    assert.equal(await fetchSource(client(`const char* s = "${marker}";`), 1), `const char* s = "${marker}";`);
}
console.log('Discussion permissions, reply quoting, and trailing source markers passed.');
