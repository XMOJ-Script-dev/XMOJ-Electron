import assert from 'node:assert/strict';
import { parseJudgeDetails, fetchSource } from '../electron/sources.ts';
import { parseUserProfile } from '../electron/profile.ts';
import { parseProblemDetail } from '../electron/problems.ts';
import { renderAnnouncement } from '../src/lib/markdown.ts';
import { userColor } from '../src/lib/user-color.ts';
import type { HttpClient } from '../electron/http.ts';
const details = parseJudgeDetails('<script>var json = {"st":0,"tasks":[{"i":"test10","s":7,"t":1000,"m":512,"sc":0},{"i":"test2","s":4,"t":2,"m":128,"sc":100}]};</script>');
assert.equal(details.tests[0].name, 'test2');
assert.equal(details.tests[1].status, 'TLE');
assert.equal(details.tests[1].timeMs, 1000);
assert.equal(details.tests[0].memoryKb, 128);
const grouped = parseJudgeDetails('<script>var json = {"st":1,"tasks":[{"i":1,"s":50,"t":[{"i":"a","s":6,"t":4,"m":20}]}]};</script>');
assert.equal(grouped.tests[0].status, 'WA');
assert.match(grouped.tests[0].group!, /子任务 1/);
assert.equal(parseJudgeDetails('无权限').tests.length, 0);
for (const body of ['<!-- not-cached -->\nint main() {}', 'int main() {}\n<!-- not-cached -->']) {
    assert.equal(await fetchSource({ get: async () => ({ status: 200, body }) } as unknown as HttpClient, 1), 'int main() {}');
}
const profileHtml = '<table id="statics"><tr><td>解决</td><td><a href="?jresult=4">2</a></td></tr><tr><td>正确</td><td><a href="?jresult=4">4</a></td></tr><tr><td>答案错误</td><td><a href="?jresult=6">3</a></td></tr></table><script>p(1,2);p(2,3);d1.push([1700000000000, 7]);d2.push([1700000000000, 4]);</script>';
const profile = parseUserProfile(profileHtml, 'alice');
assert.equal(profile.statistics?.length, 2);
assert.equal(profile.activity?.[0].submitted, 7);
assert.equal(profile.activity?.[0].accepted, 4);
assert.ok(profile.rating! > 0 && profile.rating! <= 3000);
assert.equal(userColor('liushangchen', 0), '#a855f7');
assert.equal(userColor('alice', 2400), '#dc2f5a');
assert.equal(userColor('alice', 1600), '#337cf2');
const mixed = renderAnnouncement('## 标题 <strong>内容</strong>\n\n$x_1 &lt; x_2$');
assert.match(mixed, /katex/);
assert.match(mixed, /<strong>内容<\/strong>/);
assert.ok(!/[\u0000]/.test(mixed));
const indented = renderAnnouncement('<p>\n\t1. 幻影<strong>分裂</strong>，$k &gt; 1$。\n</p>');
assert.match(indented, /katex/);
assert.ok(!indented.includes('<pre>'));
assert.ok(!indented.includes('katex-error'));
const literal = renderAnnouncement('<pre>\t$x$ &lt; n\n</pre>');
assert.ok(!literal.includes('katex'));
assert.match(literal, /\$x\$/);
const problem = parseProblemDetail('<h2>9275: 示例</h2><div class="cnt-row"><div class="cnt-row-head">描述</div><div class="cnt-row-body"><div class="content lang_cn">$a_i &lt; 0$</div></div></div>', 9275);
assert.match(problem.cards[0].html, /&lt;/);
assert.match(renderAnnouncement(problem.cards[0].html), /katex/);
console.log('Requested parser, rating, color and Markdown regressions passed.');
const forced = renderAnnouncement('## 标题\n\n公式 $x_1$\n\n<span style="color:red">HTML</span>', 'markdown');
assert.match(forced, /<h2/);
assert.match(forced, /katex/);
assert.match(forced, /<span style="color:red">HTML<\/span>/);
const fenced = renderAnnouncement('```cpp\n\t$x$\n```', 'markdown');
assert.match(fenced, /<pre><code/);
assert.ok(!fenced.includes('katex'));
assert.ok(!fenced.includes('<p><pre>'));
const htmlAndMarkdown = renderAnnouncement('<strong>公告</strong><br>\n- 第一条 $x$\n- 第二条', 'markdown');
assert.match(htmlAndMarkdown, /<ul>/);
assert.match(htmlAndMarkdown, /katex/);
