import assert from 'node:assert/strict';
import { resolveUserBadge, userBadgeStyle } from '../src/shared/user-badge.ts';
import { fetchUserInfo } from '../src/services/api.ts';
import type { UserInfo } from '../src/shared/types.ts';
const info: UserInfo = { username: 'alice', nick: null, isAdmin: false, badge: { content: '自定义标签', backgroundColor: '#123456', color: '#ffffff' } };
assert.equal(resolveUserBadge('alice', info)?.content, '自定义标签');
assert.equal(resolveUserBadge('admin', info)?.content, '自定义标签', 'custom tag takes precedence over default administrator tag');
assert.equal(resolveUserBadge('admin'), null, 'do not fabricate a placeholder badge before loading');
assert.equal(resolveUserBadge('alice', { ...info, isAdmin: true, badge: null }), null);
assert.equal(resolveUserBadge('admin', { ...info, badge: { ...info.badge!, content: '脚本管理员' } }), null);
assert.equal(resolveUserBadge('admin', info, { ...info.badge!, content: '脚本管理员' }), null);
assert.equal(resolveUserBadge('alice'), null);
assert.deepEqual(userBadgeStyle(info.badge!), { backgroundColor: '#123456', color: '#ffffff' });
assert.equal(userBadgeStyle({ content: 'unsafe', backgroundColor: 'url(test)', color: 'invalid' }).backgroundColor, '#000000');
let calls = 0;
let finish: ((info: UserInfo) => void) | undefined;
Object.assign(globalThis, { window: { xmoj: { user: { info: () => { calls++; return new Promise<UserInfo>(resolve => { finish = resolve; }); } } } } });
const first = fetchUserInfo('alice');
const duplicate = fetchUserInfo('alice');
assert.equal(calls, 1, 'deduplicate concurrent lookups');
finish!({ ...info, badge: null });
await Promise.all([first, duplicate]);
const afterLogin = fetchUserInfo('alice');
assert.equal(calls, 2, 'anonymous result must not be retained forever after login');
finish!(info);
assert.equal((await afterLogin).badge?.content, '自定义标签');
console.log('User badge precedence, colors and non-sticky user-info requests passed.');
